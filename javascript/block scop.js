{
    // Create a variable x using let and store the value 10
    let x = 10;

    // Create a constant y using const and store the value 20
    // The value of a const variable cannot be changed later
    const y = 20;

    // Print the value of x to the console
    console.log(x);

    // Print the value of y to the console
    console.log(y);
}
